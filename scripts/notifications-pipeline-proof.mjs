import { randomUUID } from "node:crypto";
import { rmSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { getDataPlane } from "../server/dataPlane.ts";
import { resolveRedisProvider } from "../server/integrations.ts";

const dbPath = "/tmp/sinai-notifications-proof.sqlite";
rmSync(dbPath, { force: true });
process.env.NODE_ENV = "test";
process.env.SQLITE_PATH = dbPath;
process.env.DATABASE_URL = "";
process.env.REDIS_URL = "redis://127.0.0.1:6379/0";
const db = getDataPlane();
const tenantId = randomUUID();
const userId = randomUUID();
const notificationId = randomUUID();
const deliveryId = randomUUID();
const now = Date.now();
db.prepare("INSERT INTO tenants (id, name, slug, created_at, updated_at) VALUES (?, ?, ?, ?, ?)").run(tenantId, "Proof Tenant", `proof-${tenantId}`, now, now);
db.prepare("INSERT INTO users (id, email, display_name, created_at, updated_at) VALUES (?, ?, ?, ?, ?)").run(userId, `proof-${userId}@example.com`, "Proof User", now, now);
db.prepare("INSERT INTO tenant_members (tenant_id, user_id, role, created_at) VALUES (?, ?, 'TENANT_OWNER', ?)").run(tenantId, userId, now);
db.prepare("INSERT INTO notifications (id, tenant_id, user_id, channel, title, body, status, created_at) VALUES (?, ?, ?, 'IN_APP', ?, ?, 'QUEUED', ?)").run(notificationId, tenantId, userId, "Pipeline", "Delivered", now);
db.prepare("INSERT INTO notification_deliveries (id, tenant_id, notification_id, provider, status, attempts, updated_at) VALUES (?, ?, ?, 'in_app', 'QUEUED', 0, ?)").run(deliveryId, tenantId, notificationId, now);
const redis = resolveRedisProvider();
const job = { type: "notification", id: randomUUID(), tenantId, notificationId, deliveryId, userId, channel: "IN_APP", title: "Pipeline", body: "Delivered" };
const queued = await redis.enqueue("notifications-proof", JSON.stringify(job), 60);
const worker = spawnSync("pnpm", ["exec", "tsx", "scripts/queue-worker.mjs"], { cwd: process.cwd(), env: { ...process.env, WORKER_QUEUE: "notifications-proof", WORKER_ONCE: "1", WORKER_MAX_ATTEMPTS: "3" }, encoding: "utf8" });
const delivered = await db.prepare("SELECT n.status AS notification_status, d.status AS delivery_status, d.attempts FROM notifications n JOIN notification_deliveries d ON d.notification_id = n.id WHERE n.id = ?").get(notificationId);
const retryJob = { ...job, id: randomUUID(), fail: true };
const dlqQueue = `notifications-proof-fail-${Date.now()}`;
await redis.del(dlqQueue);
await redis.del(`${dlqQueue}.dlq`);
await redis.enqueue(dlqQueue, JSON.stringify(retryJob), 60);
const workerRuns = [];
for (let index = 0; index < 3; index += 1) workerRuns.push(spawnSync("pnpm", ["exec", "tsx", "scripts/queue-worker.mjs"], { cwd: process.cwd(), env: { ...process.env, WORKER_QUEUE: dlqQueue, WORKER_ONCE: "1", WORKER_MAX_ATTEMPTS: "3" }, encoding: "utf8" }));
const dlq = await redis.dequeue(`${dlqQueue}.dlq`);
const dlqJob = dlq ? JSON.parse(dlq) : null;
const checks = { queued: queued === "QUEUED", worker: worker.status === 0, notificationDelivered: delivered?.notification_status === "DELIVERED", deliveryDelivered: delivered?.delivery_status === "DELIVERED", deliveryAttempts: Number(delivered?.attempts) === 1, retryWorkers: workerRuns.every(run => run.status === 0), dlqPresent: Boolean(dlqJob), dlqAttempts: Number(dlqJob?.attempts) === 3 };
console.log(JSON.stringify({ queued, workerExit: worker.status, workerOutput: worker.stdout.trim(), delivered, retryExits: workerRuns.map(run => run.status), retryOutput: workerRuns.map(run => run.stderr.trim()), dlq: dlqJob, checks }));
if (Object.values(checks).some(value => !value)) process.exit(1);
